--CATEGORIAS_CO
CREATE SEQUENCE PAGOEXPRESS.SEQ_CATEGORIAS_CO
    START WITH 22 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE OR REPLACE TRIGGER PAGOEXPRESS.TRG_CATEGORIAS_CO_ID
BEFORE INSERT ON PAGOEXPRESS.CATEGORIAS_CO
FOR EACH ROW
BEGIN
    IF :NEW.ID_CATEGORIA IS NULL THEN
        SELECT PAGOEXPRESS.SEQ_CATEGORIAS_CO.NEXTVAL INTO :NEW.ID_CATEGORIA FROM DUAL;
    END IF;
END;

ALTER TABLE PAGOEXPRESS.CATEGORIAS_CO
    ADD CONSTRAINT PK_CATEGORIAS_CO PRIMARY KEY (ID_CATEGORIA);
	
